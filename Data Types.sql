Data types are used to define the nature of data that can be stored in each column of a table.

1.Numeric Data Types:
  **Integer Types Storing integer values.
Useful: Suitable for storing numerical data such as counts, IDs, and numerical attributes. It's a basic, yet essential, data type for many database applications.
Example: INT
 **Floating-Point 

2.Date and Time Data Types:
Storing date and time information.
Useful for tracking events and timestamps in applications.It's precise and stores
both date and time information in a format that is easily readable and sortable.
DATE: Date in 'YYYY-MM-DD' format.
DATETIME: Date and time in 'YYYY-MM-DD HH:MM' format.
TIMESTAMP: Date and time, with automatic initialization and updating to the current date and time.
TIME: Time in 'HH:MM' format.
YEAR: Year in 'YYYY' format 

3.String Data Types:
CHAR: Fixed-length string. Size up to 255 characters.
VARCHAR:  Storing variable-length strings Variable-length string. Size up to 65,535 characters.
          Offers flexibility by allowing strings of varying lengths up to a specified maximum.
          It's commonly used for text fields such as names, addresses, and descriptions.
BINARY: Fixed-length binary data. Similar to CHAR.

